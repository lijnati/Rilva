/**
 * pnpm contracts:abi — writes lib/contracts/abi.ts from the compiled Hardhat artifact so the app has
 * a typed `as const` ABI without a second hand-maintained copy. Run after `pnpm contracts:compile`.
 * A contract test (historical.test.ts) fails if the exported ABI drifts from the artifact.
 */
import { readFile, writeFile } from "node:fs/promises";

const ARTIFACT = "artifacts/contracts/RilvaEscrow.sol/RilvaEscrow.json";
const OUT = "lib/contracts/abi.ts";

async function main() {
  const artifact = JSON.parse(await readFile(ARTIFACT, "utf8")) as { contractName: string; abi: unknown[] };
  const body = [
    "// GENERATED by `pnpm contracts:abi` from " + ARTIFACT + " — do not edit by hand.",
    "export const RILVA_ESCROW_ABI = " + JSON.stringify(artifact.abi, null, 2) + " as const;",
    "",
  ].join("\n");
  await writeFile(OUT, body, "utf8");
  console.log(`wrote ${OUT} (${artifact.abi.length} ABI entries from ${artifact.contractName})`);
}

main().catch((e: unknown) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
